def analyze_intent(text: str) -> str:
    """Определяет доминирующий интент запроса пользователя."""
    lower = text.lower().strip()

    # Пасхалка 1: Пингвин Тукс
    if lower in ["show me tux", "тукс", "tux", "пингвин тукс", "покажи тукса"]:
        return "easter_egg_tux"

    # Пасхалка 2: GNU/Linux Столлмана
    # Если пользователь пишет просто "linux", "линукс" или фразы вроде "что думаешь о linux"
    if lower in ["linux", "линукс", "gnu", "gnu/linux", "gnu linux"] or re.fullmatch(r"(что такое\s+)?(linux|линукс)[\?!.]*", lower):
        return "easter_egg_stallman"

    # Пасхалка 3: Сделай бочку
    if "сделай бочку" in lower or "do a barrel roll" in lower or lower == "бочка":
        return "easter_egg_barrel_roll"

    # 1. Запрос конкретной формулы I = U / R или закона Ома
    if any(p in lower for p in ["i = u / r", "i=u/r", "i = u/r", "закон ома", "сила тока", "закону ома"]):
        return "ohm_law"

    # 2. Интент запроса помощи в решении задач
    help_keywords = ["помоги", "решить", "как решить", "помогите", "не понимаю как", "реши", "подскажи решение"]
    if any(k in lower for k in help_keywords):
        return "socratic_help"

    # 3. Интент запроса определения («что такое», «что значит»)
    def_keywords = ["что такое", "что значит", "дай определение", "объясни термин", "в чем смысл", "определение"]
    if any(k in lower for k in def_keywords):
        return "definition"

    # 4. Проверка ответов ученика на предыдущий наводящий вопрос Сократа
    if any(phrase in lower for phrase in ["уменьшится в 2", "в 2 раза меньше", "уменьшится в два", "вдвое меньше", "уменьшится"]):
        return "socratic_answer_correct"
    if any(phrase in lower for phrase in ["увеличится", "вырастет", "станет больше"]):
        return "socratic_answer_needs_guidance"

    return "general"


def get_definition_response(user_text: str) -> Dict[str, Any]:
    """Генерация словарного ответа по понятиям ФГОС с вариативностью."""
    lower = user_text.lower()
    matched_term = None

    for key in FGOS_DICTIONARY:
        if key in lower:
            matched_term = FGOS_DICTIONARY[key]
            break

    if matched_term:
        intro = random.choice([
            f"Согласно школьной программе по стандартам ФГОС, вот точное научное определение понятия **{matched_term['term']}**:",
            f"Давай обратимся к верифицированному словарю учебника:\n\n**{matched_term['term']}**:",
            f"В свободной базе знаний понятие **{matched_term['term']}** сформулировано так:"
        ])
        return {
            "type": "definition",
            "title": matched_term["term"],
            "message": f"{intro}\n\n📖 {matched_term['def']}",
            "source": matched_term["source"],
            "socratic_question": "Как ты думаешь, где это явление чаще всего встречается нам в повседневной жизни?",
            "suggestions": [
                "Приведи пример из жизни",
                "Сформулируй формулу I = U / R",
                "Помоги решить задачу",
                "show me tux"
            ]
        }

    return {
        "type": "definition_fallback",
        "title": "Словарь понятий ФГОС",
        "message": (
            "Я храню свободные и точные научные определения понятий школьной программы ФГОС РФ.\n\n"
            "Попробуй спросить: *«Что такое закон Ома?»*, *«Что такое электрический ток?»*, "
            "*«Что такое фотосинтез?»* или *«Что такое теорема Пифагора?»*."
        ),
        "source": "ФГОС РФ • Свободная энциклопедия знаний",
        "suggestions": [
            "Что такое закон Ома?",
            "Что такое электрический ток?",
            "Что такое напряжение?",
            "show me tux"
        ]
    }


