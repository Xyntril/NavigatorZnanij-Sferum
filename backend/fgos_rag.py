def search_fgos_knowledge(query: str) -> Optional[Dict[str, Any]]:
    """
    Поиск по локальной базе знаний ФГОС (RAG Retrieval).
    Анализирует текст запроса на наличие ключевых формул, терминов и тематик.
    """
    normalized = query.lower().strip()
    
    # Регулярные выражения и паттерны для выявления Закона Ома: "I = U / R", "закон ома", "ток", "напряжение"
    ohm_patterns = [
        r"i\s*=\s*u\s*/\s*r",
        r"i\s*=\s*u\s*:\s*r",
        r"закон\s+ома",
        r"сила\s+тока",
        r"напряжени[ея]",
        r"сопротивлени[ея]",
        r"u\s*/\s*r",
        r"i=u/r",
        r"вольт",
        r"ампер",
        r"ом\b"
    ]
    
    for pattern in ohm_patterns:
        if re.search(pattern, normalized, re.IGNORECASE):
            return FGOS_KNOWLEDGE_BASE["ohm_law"]
            
    # Паттерны для теоремы Пифагора
    pyth_patterns = [
        r"пифагор",
        r"a\^?2\s*\+\s*b\^?2",
        r"гипотенуз",
        r"катет"
    ]
    for pattern in pyth_patterns:
        if re.search(pattern, normalized, re.IGNORECASE):
            return FGOS_KNOWLEDGE_BASE["pythagoras"]
            
    return None
