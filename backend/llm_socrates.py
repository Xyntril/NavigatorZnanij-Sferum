"""
Модуль генерации ответов методом Сократа (Socratic Method Engine).
Вместо прямой выдачи готовых решений ИИ ведет ученика через:
1. Декомпозицию проблемы на логические шаги
2. Наглядные аналогии из физического мира (вода в трубе и др.)
3. Наводящие вопросы для самостоятельного осознания сути явления
4. Строгую привязку к параграфам стандартов ФГОС
"""

from typing import Dict, Any, List
import re
from backend.fgos_rag import search_fgos_knowledge


def format_socratic_response_text(data: Dict[str, Any]) -> str:
    """Формирует структурированный текст ответа для чата."""
    lines = []
    lines.append(f"### 💡 {data.get('title', 'Разбор темы')}")
    lines.append(f"> **Определение (ФГОС):** {data.get('definition', '')}\n")
    
    lines.append("#### 🧭 Шаги для понимания:")
    for step in data.get("steps", []):
        lines.append(f"**Шаг {step['step']}. {step['title']}**\n{step['description']}\n")
        
    if "analogy" in data:
        analogy = data["analogy"]
        lines.append(f"🌊 **{analogy['title']}:**")
        lines.append(f"{analogy['narrative']}\n")
        
    if "socratic_question" in data:
        lines.append(f"🤔 **Вопрос на размышление:**\n*{data['socratic_question']}*")
        
    return "\n".join(lines)


def process_socratic_dialogue(user_text: str) -> Dict[str, Any]:
    """
    Основная точка входа диалогового агента Сократа.
    Принимает текст ученика, анализирует контекст и возвращает
    структурированный ответ с метаданными верификации ФГОС.
    """
    cleaned = user_text.strip().lower()
    
    # 1. Проверка ответа ученика на наводящий вопрос по Закону Ома
    # Вопрос был: "Как изменится сила тока, если сопротивление увеличить в 2 раза?"
    if any(phrase in cleaned for phrase in [
        "уменьшится в 2", "в 2 раза меньше", "уменьшится в два", "вдвое меньше", 
        "станет в 2 раза меньше", "уменьшится"
    ]):
        return {
            "type": "praise_and_deepen",
            "message": (
                "🎯 **Блестяще! Точно в цель!**\n\n"
                "Поскольку сопротивление $R$ находится в **знаменателе** формулы ($I = \\frac{U}{R}$), "
                "между силой тока и сопротивлением существует **обратно пропорциональная связь**.\n\n"
                "Сжали шланг в 2 раза (увеличили $R$) — воды протекает ровно в 2 раза меньше (сила тока $I$ упала)."
            ),
            "steps": [
                {"step": 1, "title": "Анализ формулы", "description": "В формуле $I = \\frac{U}{R}$ сопротивление стоит в делителе."},
                {"step": 2, "title": "Математический вывод", "description": "Если знаменатель растёт в $k$ раз, то вся дробь уменьшается в $k$ раз."}
            ],
            "analogy": {
                "title": "Физическая интуиция",
                "narrative": "Чем больше камней и препятствий на горной тропе, тем медленнее идёт отряд туристов при тех же усилиях."
            },
            "socratic_question": "А что произойдёт, если мы в 3 раза увеличим напряжение $U$, не трогая сопротивление?",
            "source": "Проверено: Физика 8 кл. (ФГОС), §44",
            "suggestions": [
                "Увеличится в 3 раза",
                "Уменьшится в 3 раза",
                "Не изменится",
                "Разберём практическую задачу"
            ]
        }

    if any(phrase in cleaned for phrase in ["увеличится", "вырастет", "станет больше"]):
        return {
            "type": "gentle_correction",
            "message": (
                "🤔 **Давай поразмышляем вместе!**\n\n"
                "Вспомни аналогию с водой в шланге: мы **увеличили сопротивление** $R$ "
                "(то есть сильнее пережали шланг или добавили в трубу фильтр с песком).\n\n"
                "Станет ли воде легче или труднее протекать сквозь препятствие?"
            ),
            "steps": [
                {"step": 1, "title": "Суть сопротивления", "description": "Сопротивление — это мера противодействия электрическому току."}
            ],
            "analogy": {
                "title": "Шланг с водой",
                "narrative": "Если наступить ногой на садовый шланг (добавить сопротивление), струя воды на выходе ослабнет или усилится?"
            },
            "socratic_question": "Так что же произойдёт с объёмом вытекающей воды в секунду (силой тока $I$)?",
            "source": "Проверено: Физика 8 кл. (ФГОС), §44",
            "suggestions": [
                "Тогда ток уменьшится в 2 раза",
                "Останется прежним",
                "Объясни формулу I = U / R заново"
            ]
        }

    # 2. Поиск в верифицированной базе знаний ФГОС (RAG)
    rag_entry = search_fgos_knowledge(cleaned)
    if rag_entry:
        return {
            "type": "educational_concept",
            "title": rag_entry.get("title", "Разбор темы"),
            "formula": rag_entry.get("formula", ""),
            "message": (
                f"Здравствуй! Давай разберём формулу **{rag_entry.get('formula')}** "
                f"не простой зубрежкой, а через понимание физического процесса.\n\n"
                f"📘 **{rag_entry.get('definition')}**"
            ),
            "steps": rag_entry.get("steps", []),
            "analogy": rag_entry.get("analogy", {}),
            "socratic_question": rag_entry.get("socratic_question", ""),
            "source": rag_entry.get("source", "ФГОС РФ"),
            "suggestions": rag_entry.get("suggestions", [])
        }

    # 3. Дефолтный ответ Сократического ассистента с приглашением к диалогу
    return {
        "type": "general_guidance",
        "title": "Навигатор Знаний",
        "message": (
            "Привет! Я твой наставник **Навигатор Знаний** по школьной программе ФГОС.\n\n"
            "Моя цель — не просто выдать тебе готовый ответ для домашнего задания, "
            "а помочь понять фундаментальные принципы науки через логику, аналогии и наводящие вопросы.\n\n"
            "Задай мне вопрос по физике или геометрии, например, спроси меня про формулу **I = U / R** или теорему Пифагора!"
        ),
        "steps": [
            {"step": 1, "title": "Задай тему", "description": "Спроси формулу или физический закон, вызывающий трудности."},
            {"step": 2, "title": "Разбери аналогию", "description": "Представь явление на наглядном бытовом примере."},
            {"step": 3, "title": "Ответь на вопрос", "description": "Сделай логический вывод самостоятельно."}
        ],
        "analogy": {
            "title": "Метод Сократа в учебе",
            "narrative": "Знание, до которого ты додумался сам с помощью наводящих вопросов, остаётся в памяти навсегда, в отличие от бездумно списанной формулы."
        },
        "socratic_question": "Хочешь узнать, как Закон Ома ($I = U / R$) объясняется через напор воды в шланге?",
        "source": "Стандарты ФГОС РФ: Физика и Математика",
        "suggestions": [
            "Что означает I = U / R?",
            "Аналогия с водой в трубе",
            "Теорема Пифагора a² + b² = c²",
            "Как работает метод Сократа?"
        ]
    }
